import path from "node:path";
import { FuzzIoElement, FuzzTests } from "../../Types";
import * as ValueMapper from "../../mappers/ValueMapper";
import * as ProgramFactory from "../../analysis/ProgramFactory";
import { AbstractProgram } from "../../analysis/AbstractProgram";
import { AbstractTestAdapter } from "../AbstractTestAdapter";

/**
 * Converts a set of NaNofuzz saved tests into an executable Virgil regression test suite.
 */
export class VirgilTestAdapter extends AbstractTestAdapter {
  protected _testSet: FuzzTests;
  protected _module: string;

  constructor(testSet: FuzzTests, module: string) {
    super();
    this._testSet = testSet;
    this._module = module;
  }

  public get toolname(): string {
    return "Virgil";
  }

  public get filename(): string {
    const ext = path.extname(this._module);
    const base = ext ? this._module.slice(0, -ext.length) : this._module;
    return `${base}_nano_test.v3`;
  }

  public toString(): string {
    const out: string[] = [];
    out.push("// Auto-generated by NaNofuzz for Virgil");
    out.push("");

    let pgm: AbstractProgram | undefined;
    try {
      pgm = ProgramFactory.fromFile(this._module, "virgil");
    } catch {
      // If parsing fails, fall back to basic synthesis
    }

    const testStatements: string[] = [];
    let testIdx = 0;

    for (const [fnName, fnData] of Object.entries(this._testSet.functions)) {
      const fnDef = pgm?.functions[fnName];
      const argDefs = fnDef?.getArgDefs() ?? [];

      for (const [, testCase] of Object.entries(fnData.tests)) {
        const mappedArgs: string[] = [];

        testCase.input.forEach((argVal: FuzzIoElement, idx: number) => {
          const argDef = argDefs[idx];
          mappedArgs.push(ValueMapper.toLang("virgil", argVal.value, argDef));
        });

        const callStr = `${fnName}(${mappedArgs.join(", ")})`;
        const outVal = testCase.output?.[0]?.value;

        if (fnData.isVoid) {
          testStatements.push(`    // Test case ${testIdx}: ${fnName}`);
          testStatements.push(`    ${callStr};`);
        } else if (outVal !== undefined) {
          const expectedStr = ValueMapper.toLang(
            "virgil",
            outVal,
            fnDef?.getReturnArg()
          );
          testStatements.push(`    // Test case ${testIdx}: ${fnName}`);
          testStatements.push(`    var res_${testIdx} = ${callStr};`);
          testStatements.push(
            `    if (res_${testIdx} != ${expectedStr}) { System.error("Test failed: res_${testIdx} != ${expectedStr}\\n"); }`
          );
        } else {
          testStatements.push(`    // Test case ${testIdx}: ${fnName}`);
          testStatements.push(`    ${callStr};`);
        }
        testIdx++;
      }
    }

    out.push("def main() -> int {");
    if (testStatements.length > 0) {
      out.push(testStatements.join("\n"));
    }
    out.push("    return 0;");
    out.push("}");
    out.push("");

    return out.join("\n");
  } // fn: toString
} // class: VirgilTestAdapter
